//
//  CurrencyCatalog.swift
//  Pocket
//
//  Shared between the app AND the widget extension.
//
//  Every fiat currency Pocket can convert: ISO code, English name, the symbol a
//  local would write, the decimals people actually use (CLDR), and a flag. It is
//  static on purpose — the list has to be there in airplane mode, and the tests
//  need it to be the same on every machine.
//
//  Generated once from Foundation's locale data (the symbol a currency's home
//  locale uses, and CLDR's decimals), then hand-tuned: Arabic-script symbols become Latin abbreviations (they
//  reorder badly inside left-to-right text), "$" currencies get a prefix so two
//  dollars never look alike, and CFA/East Caribbean currencies get a globe
//  because no single country's flag is right for them.
//

